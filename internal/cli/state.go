package cli

import (
	"crypto/rand"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"time"

	"github.com/bochkarevart/1c-selection/internal/model"
)

type pendingNote struct {
	Server   string            `json:"server"`
	ClientID int64             `json:"client_id"`
	SavedAt  time.Time         `json:"saved_at"`
	Note     model.NoteRequest `json:"note"`
}

var requestIDPattern = regexp.MustCompile(`^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$`)

func newRequestID() (string, error) {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", fmt.Errorf("generate request ID: %w", err)
	}
	b[6] = b[6]&0x0f | 0x40
	b[8] = b[8]&0x3f | 0x80
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16]), nil
}

func atomicJSON(path string, value any) error {
	dir := filepath.Dir(path)
	if err := privateDirectory(dir); err != nil {
		return err
	}
	f, err := os.CreateTemp(dir, ".times-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	defer f.Close()
	if err := f.Chmod(0o600); err != nil {
		return err
	}
	if err := json.NewEncoder(f).Encode(value); err != nil {
		return err
	}
	if err := f.Sync(); err != nil {
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Rename(f.Name(), path); err != nil {
		return err
	}
	return syncDirectory(dir)
}

func privateDirectory(path string) error {
	if err := os.MkdirAll(path, 0o700); err != nil {
		return err
	}
	return os.Chmod(path, 0o700)
}

func syncDirectory(path string) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return f.Sync()
}

func readJSON(path string, value any) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	return json.Unmarshal(data, value)
}

func (a *app) pendingPath(id string) (string, error) {
	if !requestIDPattern.MatchString(id) {
		return "", errors.New("request ID must be a UUID generated by times note send")
	}
	return filepath.Join(a.stateDir, "outbox", id+".json"), nil
}

func (a *app) pending() ([]pendingNote, error) {
	entries, err := os.ReadDir(filepath.Join(a.stateDir, "outbox"))
	if errors.Is(err, os.ErrNotExist) {
		return []pendingNote{}, nil
	}
	if err != nil {
		return nil, err
	}
	notes := make([]pendingNote, 0, len(entries))
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".json" {
			continue
		}
		var note pendingNote
		if err := readJSON(filepath.Join(a.stateDir, "outbox", entry.Name()), &note); err != nil {
			return nil, fmt.Errorf("read pending note %s: %w", entry.Name(), err)
		}
		if entry.Name() != note.Note.RequestID+".json" || !requestIDPattern.MatchString(note.Note.RequestID) {
			return nil, fmt.Errorf("invalid pending note %s", entry.Name())
		}
		notes = append(notes, note)
	}
	sort.Slice(notes, func(i, j int) bool {
		if notes[i].SavedAt.Equal(notes[j].SavedAt) {
			return notes[i].Note.RequestID < notes[j].Note.RequestID
		}
		return notes[i].SavedAt.Before(notes[j].SavedAt)
	})
	return notes, nil
}
